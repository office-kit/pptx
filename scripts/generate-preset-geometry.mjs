// Generates src/internal/drawingml/preset-geometry.generated.ts from the
// ECMA-376 preset shape definitions (Part 1, Annex D, presetShapeDefinitions.xml),
// shipped in the `references/ecma-376-5th` submodule.
//
//   git submodule update --init --depth 1 references/ecma-376-5th
//   node scripts/generate-preset-geometry.mjs
//   pnpm exec oxfmt src/internal/drawingml/preset-geometry.generated.ts
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = new URL(
  '../references/ecma-376-5th/ECMA-376/OfficeOpenXML-DrawingMLGeometries/presetShapeDefinitions.xml',
  import.meta.url,
);
const TARGET = new URL('../src/internal/drawingml/preset-geometry.generated.ts', import.meta.url);

// The definitions file is plain element/attribute markup (no text content,
// CDATA or entities beyond attribute values), so a small tokenizer is enough.
function parse(xml) {
  const root = { name: '#root', attrs: {}, children: [] };
  const stack = [root];
  const tag =
    /<(\/?)([A-Za-z0-9_:]+)((?:\s+[A-Za-z0-9_:]+="[^"]*")*)\s*(\/?)>|<\?[^>]*\?>|<!--[\s\S]*?-->/g;
  for (const match of xml.matchAll(tag)) {
    if (!match[2]) continue;
    const [, closing, name, rawAttrs, selfClosing] = match;
    if (closing) {
      stack.pop();
      continue;
    }
    const attrs = {};
    for (const [, key, value] of rawAttrs.matchAll(/([A-Za-z0-9_:]+)="([^"]*)"/g))
      attrs[key] = value;
    const node = { name, attrs, children: [] };
    stack.at(-1).children.push(node);
    if (!selfClosing) stack.push(node);
  }
  return root.children[0];
}

const child = (node, name) => node.children.find((c) => c.name === name);
const guides = (list) => (list ? list.children.map((gd) => [gd.attrs.name, gd.attrs.fmla]) : []);
const point = (pt) => [pt.attrs.x, pt.attrs.y];

function command(c) {
  switch (c.name) {
    case 'moveTo':
      return ['M', ...point(c.children[0])];
    case 'lnTo':
      return ['L', ...point(c.children[0])];
    case 'arcTo':
      return ['A', c.attrs.wR, c.attrs.hR, c.attrs.stAng, c.attrs.swAng];
    case 'quadBezTo':
      return ['Q', ...c.children.flatMap(point)];
    case 'cubicBezTo':
      return ['C', ...c.children.flatMap(point)];
    case 'close':
      return ['Z'];
    default:
      throw new Error(`Unknown path command <${c.name}>`);
  }
}

function path(p) {
  const out = { commands: p.children.map(command) };
  if (p.attrs.w !== undefined) out.w = Number(p.attrs.w);
  if (p.attrs.h !== undefined) out.h = Number(p.attrs.h);
  if (p.attrs.fill !== undefined && p.attrs.fill !== 'norm') out.fill = p.attrs.fill;
  if (p.attrs.stroke === 'false' || p.attrs.stroke === '0') out.stroke = false;
  return out;
}

const definitions = parse(readFileSync(SOURCE, 'utf8').replace(/^\uFEFF/, ''));
const presets = {};
for (const shape of definitions.children) {
  const rect = child(shape, 'rect');
  const def = {
    av: guides(child(shape, 'avLst')),
    gd: guides(child(shape, 'gdLst')),
    paths: child(shape, 'pathLst').children.map(path),
  };
  if (rect) def.rect = [rect.attrs.l, rect.attrs.t, rect.attrs.r, rect.attrs.b];
  presets[shape.name] = def;
}

// The published file defines `upDownArrow` twice and `upArrow` not at all.
// This is `downArrow` mirrored top to bottom, the same way `leftArrow`
// mirrors `rightArrow`, and it is the outline the reference desktop app draws.
presets.upArrow = {
  av: [
    ['adj1', 'val 50000'],
    ['adj2', 'val 50000'],
  ],
  gd: [
    ['maxAdj2', '*/ 100000 h ss'],
    ['a1', 'pin 0 adj1 100000'],
    ['a2', 'pin 0 adj2 maxAdj2'],
    ['dy2', '*/ ss a2 100000'],
    ['y2', '+- t dy2 0'],
    ['dx1', '*/ w a1 200000'],
    ['x1', '+- hc 0 dx1'],
    ['x2', '+- hc dx1 0'],
    ['dy1', '*/ x1 dy2 wd2'],
    ['y1', '+- y2 0 dy1'],
  ],
  paths: [
    {
      commands: [
        ['M', 'l', 'y2'],
        ['L', 'hc', 't'],
        ['L', 'r', 'y2'],
        ['L', 'x2', 'y2'],
        ['L', 'x2', 'b'],
        ['L', 'x1', 'b'],
        ['L', 'x1', 'y2'],
        ['Z'],
      ],
    },
  ],
  rect: ['x1', 'y1', 'x2', 'b'],
};

writeFileSync(
  TARGET,
  `// Generated by scripts/generate-preset-geometry.mjs from ECMA-376 Part 1
// presetShapeDefinitions.xml. Do not edit by hand.

import type { PresetGeometryDefinition } from './preset-geometry.ts';

export const PRESET_GEOMETRY: Readonly<Record<string, PresetGeometryDefinition>> = ${JSON.stringify(presets)};
`,
);
console.log(`Wrote ${Object.keys(presets).length} presets`);

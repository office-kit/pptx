// Generates src/internal/presentationml/builtin-table-styles.generated.ts from
// the reference desktop app's own serialization of its 74 built-in table styles, checked in as
// test/fixtures/native/builtin-table-styles.xml (provenance in
// test/fixtures/SOURCES.md).
//
//   node scripts/generate-builtin-table-styles.mjs
//   pnpm exec oxfmt src/internal/presentationml/builtin-table-styles.generated.ts
//
// The accent variants of a family differ only in which accent they reference,
// so each family is stored once with `$A` / `$B` in place of that accent.
// test/builtin-table-styles.test.ts expands every style again and compares it
// with the fixture byte for byte.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = new URL('../test/fixtures/native/builtin-table-styles.xml', import.meta.url);
const TARGET = new URL(
  '../src/internal/presentationml/builtin-table-styles.generated.ts',
  import.meta.url,
);

const xml = readFileSync(SOURCE, 'utf8');
const styles = [
  ...xml.matchAll(
    /<a:tblStyle styleId="(\{[^"]+\})" styleName="([^"]+)">([\s\S]*?)<\/a:tblStyle>/g,
  ),
].map(([, id, name, body]) => ({ id, name, body }));
if (styles.length !== 74) throw new Error(`expected 74 built-in styles, found ${styles.length}`);

const category = (name) => {
  if (name.startsWith('Themed Style') || name.startsWith('No Style')) return 'bestMatch';
  if (name.startsWith('Light Style')) return 'light';
  if (name.startsWith('Medium Style')) return 'medium';
  if (name.startsWith('Dark Style')) return 'dark';
  throw new Error(`unknown table style family: ${name}`);
};

const bodies = [];
const definitions = styles.map(({ id, name, body }) => {
  const pair = /Accent (\d)\/Accent (\d)$/.exec(name);
  const single = /Accent (\d)$/.exec(name);
  const accentA = Number(pair?.[1] ?? single?.[1] ?? 0);
  const accentB = Number(pair?.[2] ?? 0);
  let template = body;
  if (accentA) template = template.replaceAll(`val="accent${accentA}"`, 'val="$A"');
  if (accentB) template = template.replaceAll(`val="accent${accentB}"`, 'val="$B"');
  let index = bodies.indexOf(template);
  if (index < 0) index = bodies.push(template) - 1;
  return { id, name, index, accentA, accentB };
});

const out = [
  '// GENERATED by scripts/generate-builtin-table-styles.mjs from',
  '// test/fixtures/native/builtin-table-styles.xml — the reference desktop app’s own serialization',
  '// of its built-in table styles as captured by Dewiride PPTX Studio, Copyright 2026',
  '// Dewiride Technologies, Apache-2.0 — attribution, modifications and license text in',
  '// THIRD_PARTY_NOTICES.md; provenance in test/fixtures/SOURCES.md. Do not edit.',
  '',
  '/** The reference desktop app’s built-in table styles, in the order of its Table Styles gallery. */',
  'export const BUILTIN_TABLE_STYLES = [',
  ...styles.map(
    ({ id, name }) => `  { id: '${id}', name: '${name}', category: '${category(name)}' },`,
  ),
  '] as const;',
  '',
  '// Family bodies (the children of `a:tblStyle`). `$A` / `$B` stand for the',
  '// accent color(s) a variant references.',
  'export const BUILTIN_TABLE_STYLE_BODIES: ReadonlyArray<string> = [',
  ...bodies.map((body) => `  ${JSON.stringify(body)},`),
  '];',
  '',
  '// Style GUID -> [body index, accent standing for `$A`, accent standing for `$B`].',
  'export const BUILTIN_TABLE_STYLE_DEFINITIONS: Readonly<',
  '  Record<string, readonly [body: number, accentA: number, accentB: number]>',
  '> = {',
  ...definitions.map(
    ({ id, index, accentA, accentB }) => `  '${id}': [${index}, ${accentA}, ${accentB}],`,
  ),
  '};',
  '',
];
writeFileSync(TARGET, out.join('\n'));

// Generates src/internal/drawingml/builtin-picture-styles.generated.ts from
// The reference desktop app's own output for its 28 Picture Styles, checked in as
// test/fixtures/native/picture-styles/NN-*.xml (provenance in
// test/fixtures/SOURCES.md).
//
//   node scripts/generate-builtin-picture-styles.mjs
//   pnpm exec oxfmt src/internal/drawingml/builtin-picture-styles.generated.ts
//
// Each fixture is the whole `p:pic` the reference desktop app saved after applying one style
// to a plain picture. A style only writes `p:spPr` after `a:xfrm`, so that is
// what is kept. test/builtin-picture-styles.test.ts applies every style again
// and compares the result with the fixture byte for byte.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const SOURCE = new URL('../test/fixtures/native/picture-styles/', import.meta.url);
const TARGET = new URL(
  '../src/internal/drawingml/builtin-picture-styles.generated.ts',
  import.meta.url,
);

const files = readdirSync(SOURCE)
  .filter((file) => /^\d\d-.*\.xml$/.test(file))
  .sort();
if (files.length !== 28) throw new Error(`expected 28 picture styles, found ${files.length}`);

const styles = files.map((file, index) => {
  const xml = readFileSync(new URL(file, SOURCE), 'utf8');
  const header = /Picture Style "([^"]+)" \(gallery index (\d+)\)/.exec(xml);
  if (!header || Number(header[2]) !== index) throw new Error(`${file}: unexpected header`);
  const spPr = /<p:spPr><a:xfrm>.*?<\/a:xfrm>(.*)<\/p:spPr>/.exec(xml);
  if (!spPr) throw new Error(`${file}: no spPr`);
  return { name: header[1], spPr: spPr[1] };
});

const out = `// GENERATED by scripts/generate-builtin-picture-styles.mjs from
// test/fixtures/native/picture-styles/ — what the reference desktop app (Mac 16.113) writes into
// \`p:spPr\` (after \`a:xfrm\`) for each built-in Picture Style; provenance in
// test/fixtures/SOURCES.md. Do not edit.

/** The reference desktop app's built-in picture styles, in the order of its Picture Styles gallery. */
export const BUILTIN_PICTURE_STYLES = ${JSON.stringify(styles.map((style) => style.name))} as const;

/** The \`p:spPr\` children each style writes after \`a:xfrm\`, in gallery order. */
export const BUILTIN_PICTURE_STYLE_SP_PR: readonly string[] = ${JSON.stringify(
  styles.map((style) => style.spPr),
)};
`;
writeFileSync(TARGET, out);
